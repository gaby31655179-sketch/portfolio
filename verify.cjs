const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(`${__dirname}/index.html`, 'utf8');
const code = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(item => item[1]).join('\n');
const nodes = new Map();
const document = { querySelector(selector) {
  if(!nodes.has(selector)) nodes.set(selector, { innerHTML: '', textContent: '', attrs: {}, setAttribute(key, value){this.attrs[key]=value;}, removeAttribute(key){delete this.attrs[key]; if(key==='href') delete this.href;} });
  return nodes.get(selector);
} };
const context = {document, URL, window:{}, location:{href:'file:///C:/portfolio/index.html',protocol:'file:'}};
vm.createContext(context); vm.runInContext(code, context);
assert.deepEqual([...html.matchAll(/<section[^>]*id="([^"]+)"/g)].map(item => item[1]), ['projects', 'resume']);
assert.equal((nodes.get('#project-grid').innerHTML.match(/class="card"/g)||[]).length, 3);
assert.ok(!nodes.get('#project-grid').innerHTML.includes('class="project-link"'));
assert.equal(nodes.get('#resume-download').attrs['aria-disabled'], 'true');
assert.equal(nodes.get('#resume-download').href, undefined);
vm.runInContext("PROFILE.resumeUrl='resume.pdf'; PROJECTS[0].url='report.pdf'; renderProjects(); renderResume();", context);
assert.equal(nodes.get('#resume-download').href, 'file:///C:/portfolio/resume.pdf');
assert.equal(nodes.get('#resume-download').attrs.download, 'Che-Wei-Chang-Resume.pdf');
assert.ok(nodes.get('#project-grid').innerHTML.includes('file:///C:/portfolio/report.pdf'));
assert.equal(vm.runInContext("safeURL('javascript:alert(1)')", context), '');
assert.equal(vm.runInContext("safeURL('')", context), '');
context.location = {href:'https://example.github.io/portfolio/',protocol:'https:'};
assert.equal(vm.runInContext("safeURL('/uploads/documents/resume.pdf')", context), 'https://example.github.io/portfolio/uploads/documents/resume.pdf');
assert.equal(vm.runInContext("safeURL('file:///C:/private.txt')", context), '');
vm.runInContext("PROJECTS[0].file='/uploads/documents/work.pdf'; renderProjects();", context);
assert.ok(nodes.get('#project-grid').innerHTML.includes('https://example.github.io/portfolio/uploads/documents/work.pdf'));
vm.runInContext("PROJECTS[0].title='<script>unsafe</script>'; renderProjects();", context);
assert.ok(nodes.get('#project-grid').innerHTML.includes('&lt;script&gt;unsafe&lt;/script&gt;'));
assert.ok(!html.includes('AI 協作'));
const built = fs.readFileSync(`${__dirname}/_site/index.html`, 'utf8');
const builtCode = [...built.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(item => item[1]).join('\n');
const builtContext = {document, URL, window:{}, location:{href:'https://example.github.io/portfolio/',protocol:'https:'}};
vm.createContext(builtContext); vm.runInContext(builtCode, builtContext);
const stored = JSON.parse(fs.readFileSync(`${__dirname}/data/resume.json`, 'utf8'));
assert.equal(nodes.get('#resume-name').textContent, stored.name);
assert.equal(nodes.get('#resume-education').textContent, stored.education || '待補充');
const editable = fs.readFileSync(`${__dirname}/.pages.yml`, 'utf8');
assert.ok(editable.includes('path: data/projects.json'));
assert.ok(editable.includes('path: data/resume.json'));
assert.ok(fs.existsSync(`${__dirname}/_site/admin/index.html`));
assert.ok(!fs.existsSync(`${__dirname}/_site/.pages.yml`));
assert.ok(!fs.existsSync(`${__dirname}/_site/data/resume.json`));
assert.ok(fs.existsSync(`${__dirname}/_site/uploads/documents`));
// Verify edited text and an empty portfolio reach the visitor page.
const edited = {profile:{...stored,name:'測試姓名',education:'新的學歷',resumeUrl:'/uploads/documents/resume.pdf'},projects:[]};
const editedContext = {document,URL,window:{PORTFOLIO_CONTENT:edited},location:{href:'https://example.github.io/portfolio/',protocol:'https:'}};
vm.createContext(editedContext); vm.runInContext(code,editedContext);
assert.equal(nodes.get('#resume-name').textContent,'測試姓名');
assert.equal(nodes.get('#resume-education').textContent,'新的學歷');
assert.equal(nodes.get('#resume-download').href,'https://example.github.io/portfolio/uploads/documents/resume.pdf');
assert.ok(nodes.get('#project-grid').innerHTML.includes('作品即將加入'));
console.log('PASS: CMS content rendering, updated resume, PDF links, GitHub Pages subpaths, empty projects, safe content, deployment package.');
